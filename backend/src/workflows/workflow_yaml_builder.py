"""Generates the GCP Workflows YAML of a workflow definition.

Pure functions (no I/O). The generated YAML:

* passes ``run_id`` / ``step_id`` / ``execution_id`` to every executor call,
  so the executor checkpoints the step and reuses its generation job;
* gates every step with a ``switch`` that skips it when ``<step>_out`` is
  already set from ``prior_outputs`` (resume); downstream references read
  ``<step>_out`` instead of the call result;
* reads ``prior_outputs`` from the execution arguments or, when
  ``fetch_checkpoint`` is set, from ``GET /runs/{run_id}/checkpoint``;
* retries transient failures natively: connection errors, timeouts and
  HTTP 429 / 500 / 502 / 503 / 504, incl. 504 ``STEP_IN_PROGRESS``, unless
  the executor answers ``retry_safe: false``;
* sets an explicit ``timeout`` on every step call (Cloud Run limit);
* reports the outcome to ``POST /runs/{run_id}/finished``. Callback
  failures are swallowed (the reconciler covers missed callbacks).

Executions without ``run_id`` skip the checkpoint and both callbacks.
"""

